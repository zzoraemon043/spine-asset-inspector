import { test, expect, pause, readFrame, readTime, stageShot } from './fixtures'

test.describe('motion player and playback controller', () => {
  test('switches animations from the list', async ({ app }) => {
    await app.getByTestId('animation-item-walk').click()
    await expect(app.getByTestId('animation-item-walk')).toHaveAttribute('aria-selected', 'true')
    await expect(app.getByTestId('stage-hud')).toContainText('walk')
    await expect(app.getByTestId('timeline-marker')).toHaveCount(2)
    await app.getByTestId('animation-item-attack').click()
    await expect(app.locator('[data-testid="timeline-marker"][data-event="hit"]')).toHaveCount(1)
  })

  test('pauses, steps frame by frame and steps back', async ({ app }) => {
    await app.getByTestId('animation-item-run').click()
    await pause(app)
    await app.getByTestId('timeline').click({ position: { x: 2, y: 10 } })
    const start = await readFrame(app)
    await app.getByTestId('step-forward').click()
    await expect.poll(() => readFrame(app)).toBe(start + 1)
    await app.getByTestId('step-forward').click()
    await app.getByTestId('step-forward').click()
    await expect.poll(() => readFrame(app)).toBe(start + 3)
    await app.getByTestId('step-back').click()
    await expect.poll(() => readFrame(app)).toBe(start + 2)
    const frozen = await readTime(app)
    await app.waitForTimeout(300)
    expect(await readTime(app)).toBe(frozen)
  })

  test('scrubs the timeline to an exact position', async ({ app }) => {
    await app.getByTestId('animation-item-walk').click()
    await pause(app)
    const box = await app.getByTestId('timeline').boundingBox()
    if (!box) throw new Error('timeline missing')
    await app.mouse.move(box.x + box.width * 0.1, box.y + box.height / 2)
    await app.mouse.down()
    await app.mouse.move(box.x + box.width * 0.5, box.y + box.height / 2, { steps: 5 })
    await app.mouse.up()
    await expect.poll(() => readTime(app)).toBeGreaterThan(0.47)
    expect(await readTime(app)).toBeLessThan(0.53)
    expect(await readFrame(app)).toBeGreaterThanOrEqual(14)
    expect(await readFrame(app)).toBeLessThanOrEqual(16)
    await expect(app.getByTestId('play-toggle')).toHaveAttribute('data-state', 'paused')
  })

  test('changes speed, loop and responds to keyboard shortcuts', async ({ app }) => {
    await app.getByTestId('speed-0.1').click()
    await expect(app.getByTestId('speed-value')).toHaveText('0.10x')
    await app.getByTestId('speed-2').click()
    await expect(app.getByTestId('speed-value')).toHaveText('2.00x')
    await app.getByTestId('speed-slider').fill('0.5')
    await expect(app.getByTestId('speed-value')).toHaveText('0.50x')
    await expect(app.getByTestId('loop-toggle')).toHaveAttribute('aria-pressed', 'true')
    await app.getByTestId('loop-toggle').click()
    await expect(app.getByTestId('loop-toggle')).toHaveAttribute('aria-pressed', 'false')
    await app.getByTestId('stage-canvas').click()
    await app.keyboard.press('Space')
    await expect(app.getByTestId('play-toggle')).toHaveAttribute('data-state', 'paused')
    const frame = await readFrame(app)
    await app.keyboard.press('ArrowRight')
    await expect.poll(() => readFrame(app)).toBe(frame + 1)
    await app.keyboard.press('Home')
    await expect.poll(() => readFrame(app)).toBe(0)
    await app.keyboard.press('KeyL')
    await expect(app.getByTestId('loop-toggle')).toHaveAttribute('aria-pressed', 'true')
  })

  test('zooms, pans and resets the viewport', async ({ app }) => {
    await pause(app)
    const before = await stageShot(app)
    await app.getByTestId('zoom-in').click()
    await app.getByTestId('zoom-in').click()
    await expect(app.getByTestId('zoom-level')).not.toHaveText('100%')
    const zoomed = await stageShot(app)
    expect(zoomed.equals(before)).toBe(false)
    await app.getByTestId('reset-zoom').click()
    await expect(app.getByTestId('zoom-level')).toHaveText('100%')
    const canvas = await app.getByTestId('stage-canvas').boundingBox()
    if (!canvas) throw new Error('canvas missing')
    await app.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2)
    await app.mouse.wheel(0, -400)
    await expect(app.getByTestId('zoom-level')).not.toHaveText('100%')
    await app.getByTestId('fit-view').click()
    await app.getByTestId('background-light').click()
    await expect(app.getByTestId('stage')).toHaveClass(/stage-light/)
  })
})
